const { Router } = require('express');
const c = require('../controllers/operations.controller');
const requireOperator = require('../middleware/require-operator.middleware');
const requireRenter = require('../middleware/require-renter.middleware');
const requireManager = require('../middleware/require-management-role.middleware')('manager');
const operator = Router(); operator.use(requireOperator);
operator.get('/cancellations', c.list('cancellations'));
operator.get('/incidents', c.list('incidents'));
operator.get('/refunds', c.list('refunds'));
operator.get('/bookings/:id', c.bookingOperations);
operator.get('/bookings/:id/cancellation-preview', c.cancellationPreview);
operator.post('/bookings/:id/cancellation', c.requestCancellation);
operator.post('/bookings/:id/cancellation-decision', c.decideCancellation);
operator.post('/bookings/:id/incidents', c.reportIncident);
operator.post('/incidents/:id/proposal', c.proposeIncident);
operator.post('/incidents/:id/replace-driver', c.replaceDriver);
operator.post('/incidents/:id/resolve', c.resolveIncident);
const renter = Router(); renter.use(requireRenter);
renter.get('/:id/operations', c.bookingOperations);
renter.get('/:id/cancellation-preview', c.cancellationPreview);
renter.post('/:id/cancellation', c.requestCancellation);
renter.post('/:id/incidents', c.reportIncident);
const manager = Router(); manager.use(requireManager);
manager.get('/cancellations', c.list('cancellations'));
manager.post('/bookings/:id/cancellation-decision', c.decideCancellation);
manager.get('/incidents', c.list('incidents'));
manager.get('/refunds', c.list('refunds'));
manager.post('/incidents/:id/decision', c.approveIncident);
manager.post('/refunds/:id/decision', c.refundDecision);
module.exports = { operator, renter, manager };
