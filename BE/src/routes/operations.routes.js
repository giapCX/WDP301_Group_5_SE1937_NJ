const { Router } = require('express');
const c = require('../controllers/operations.controller');
const requireOperator = require('../middleware/require-operator.middleware');
const requireRenter = require('../middleware/require-renter.middleware');
const requireManagementRole = require('../middleware/require-management-role.middleware');
const requireManager = requireManagementRole('manager');
const { requirePermission } = requireManagementRole;
const { requireRolePermission } = requireManagementRole;
const operator = Router(); operator.use(requireOperator);
operator.get('/cancellations', requireRolePermission('booking.read.all'), c.list('cancellations'));
operator.get('/incidents', requireRolePermission('booking.read.all'), c.list('incidents'));
operator.get('/refunds', requireRolePermission('booking.read.all'), c.list('refunds'));
operator.get('/bookings/:id', requireRolePermission('booking.read.all'), c.bookingOperations);
operator.get('/bookings/:id/cancellation-preview', requireRolePermission('booking.read.all'), c.cancellationPreview);
operator.post('/bookings/:id/cancellation', requireRolePermission('booking.review'), c.requestCancellation);
operator.post('/bookings/:id/cancellation-decision', requireRolePermission('booking.review'), c.decideCancellation);
operator.post('/bookings/:id/incidents', requireRolePermission('booking.review'), c.reportIncident);
operator.post('/incidents/:id/proposal', requireRolePermission('booking.review'), c.proposeIncident);
operator.post('/incidents/:id/replace-driver', requireRolePermission('booking.review'), c.replaceDriver);
operator.post('/incidents/:id/resolve', requireRolePermission('booking.review'), c.resolveIncident);
const renter = Router(); renter.use(requireRenter, requireRolePermission('booking.read.own'));
renter.get('/:id/operations', c.bookingOperations);
renter.get('/:id/cancellation-preview', c.cancellationPreview);
renter.post('/:id/cancellation', c.requestCancellation);
renter.post('/:id/incidents', c.reportIncident);
const manager = Router(); manager.use(requireManager);
manager.get('/cancellations', requirePermission('booking.review'), c.list('cancellations'));
manager.post('/bookings/:id/cancellation-decision', requirePermission('booking.review'), c.decideCancellation);
manager.get('/incidents', requirePermission('booking.review'), c.list('incidents'));
manager.get('/refunds', requirePermission('payment.manage'), c.list('refunds'));
manager.post('/incidents/:id/decision', requirePermission('booking.review'), c.approveIncident);
manager.post('/refunds/:id/decision', requirePermission('payment.manage'), c.refundDecision);
module.exports = { operator, renter, manager };
