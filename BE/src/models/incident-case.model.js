import { Schema } from 'mongoose';
import { createSchema, embedded, arrayOf } from './schema.js';

const { ObjectId } = Schema.Types;

export const incidentCaseSchema = createSchema({
  case_number: { type: String, required: true },
  reported_by_user_id: { type: ObjectId, ref: 'User' },
  assigned_operation_staff_id: { type: ObjectId, ref: 'User' },
  report_source: String,
  operator_received_at: Date,
  response_checklist: embedded({
    driverName: String,
    injuryStatus: String,
    ownerNotifiedAt: Date,
    insurerNotifiedAt: Date,
    policeReference: String,
    insurerReference: String,
    missingDocuments: String,
    fieldResponder: String,
    driverVerification: String,
    detentionProgress: String,
    insuranceProgress: String,
    repairProgress: String,
  }),
  reviewed_by_manager_id: { type: ObjectId, ref: 'User' },
  vehicle_id: { type: ObjectId, ref: 'Vehicle', required: true },
  booking_id: { type: ObjectId, ref: 'Booking' },
  case_type: String,
  incident_type: String,
  location: embedded({ latitude: Number, longitude: Number }),
  odometer_km: Number,
  severity: { type: String, enum: ['low', 'medium', 'high'] },
  vehicle_seized: Boolean,
  source_withdrawal_id: { type: ObjectId, ref: 'VehicleWithdrawalRequest' },
  source_handover_id: { type: ObjectId, ref: 'RentalHandover' },
  request_key: String,
  request_fingerprint: String,
  description: { type: String, required: true },
  evidence: arrayOf(embedded({
    kind: String,
    file_key: String,
    file_name: String,
    content_type: String,
    uploaded_by_user_id: { type: ObjectId, ref: 'User' },
    uploaded_at: Date,
  })),
  investigation: embedded({
    review_status: String,
    renter_response: String,
  }),
  submitted_to_manager_by_user_id: { type: ObjectId, ref: 'User' },
  submitted_to_manager_at: Date,
  traffic_violation_details: embedded({
    reported_at: Date,
    notice_number: String,
    official_confirmation: String,
    fine_amount_claimed: Number,
    reviewed_by_operation_staff_id: { type: ObjectId, ref: 'User' },
    reviewed_at: Date,
    operation_recommendation: String,
    operation_recommended_penalty_fee: Number,
    operation_review_note: String,
    penalty_fee: Number,
  }),
  compensation_claims: arrayOf(embedded({
    category: String,
    settlement_party: String,
    insurance_amount: Number,
    requested_amount: Number,
    proposed_amount: Number,
    approved_amount: Number,
    decision: String,
    decision_at: Date,
    reviewed_by_manager_id: { type: ObjectId, ref: 'User' },
    renter_response: String,
    evidence_basis: String,
    manager_note: String,
    contract_basis: String,
    evidence_reference: String,
    settlement_status: String,
    settlement_reference: String,
    settled_at: Date,
    settled_by_manager_id: ObjectId,
  })),
  resolution: embedded({
    outcome: String,
    amount: Number,
    resolved_at: Date,
    note: String,
  }),
  operation_timeline: arrayOf(embedded({
    action: String,
    status: String,
    note: String,
    actor_user_id: { type: ObjectId, ref: 'User' },
    at: Date,
  })),
  handled_by: { type: ObjectId, ref: 'User' },
  handled_at: Date,
  status: String,
  created_at: Date,
  updated_at: Date,
});
